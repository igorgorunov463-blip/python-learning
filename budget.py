print("--- Калькулятор бюджета ---")

# 1. Спрашиваем доход
income = float(input("Сколько ты зарабатываешь в месяц? "))

# 2. Спрашиваем обязательные расходы
macbook = float(input("Сколько уходит на рассрочку за MacBook? "))
living = float(input("Сколько уходит на еду и жизнь? "))

# 3. Считаем остаток
total_expenses = macbook + living
remainder = income - total_expenses

# 4. Выводим результат
print("\n--- Результат ---")
print("Твой доход:", income)
print("Всего расходов:", total_expenses)
print("Остаток на накопления:", remainder)

# 5. Условие: если остаток больше 50к, выводим одно, если меньше - другое
if remainder >= 50000:
    print("Отлично! Ты откладываешь достаточно для переезда в Питер.")
else:
    print("Пока откладывается маловато, нужно оптимизировать расходы.")